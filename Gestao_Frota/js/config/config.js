        // API BASE (Suporte a Wi-Fi, IP Dinâmico e modo GitHub Pages / Cloud)
        // ================================================================
        const API_BASE = (function() {
            const urlParams = new URLSearchParams(window.location.search);
            const paramApi = urlParams.get('api') || urlParams.get('server');
            if (paramApi) {
                let formatted = paramApi.trim();
                if (!formatted.startsWith('http://') && !formatted.startsWith('https://')) {
                    formatted = 'http://' + formatted;
                }
                localStorage.setItem('sf_custom_api_base', formatted);
                return formatted;
            }
            const savedApi = localStorage.getItem('sf_custom_api_base');
            if (savedApi) return savedApi;
            if (window.location.protocol === 'file:' || window.location.hostname.includes('github.io')) {
                return 'http://127.0.0.1:8000';
            }
            return window.location.origin.includes('8000') ? window.location.origin : 'http://127.0.0.1:8000';
        })();

        function promptChangeServerIp() {
            const current = localStorage.getItem('sf_custom_api_base') || API_BASE || 'http://127.0.0.1:8000';
            const input = prompt(
                "Endereço IP do DataServer (Servidor de Banco de Dados):\n\n" +
                "Insira o IP do servidor para autenticação e sincronização (exemplo: http://127.0.0.1:8000 ou http://seu-ip:8000):",
                current
            );
            if (input !== null && input.trim() !== '') {
                let formatted = input.trim();
                if (!formatted.startsWith('http://') && !formatted.startsWith('https://')) {
                    formatted = 'http://' + formatted;
                }
                localStorage.setItem('sf_custom_api_base', formatted);
                alert("IP do DataServer configurado para: " + formatted + "\nA página será recarregada agora.");
                window.location.reload();
            }
        }

        function updateServerIpBadge() {
            const el = document.getElementById('lblServerIpDisplay');
            if (el) el.textContent = API_BASE;
        }
        document.addEventListener('DOMContentLoaded', updateServerIpBadge);
        setTimeout(updateServerIpBadge, 300);

